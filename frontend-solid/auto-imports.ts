import { createRequire } from "node:module";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import ts from "typescript";

export function getSolidImports() {
  const require = createRequire(import.meta.url);
  const packagePath = require.resolve("solid-js/package.json");
  const declarationPath = join(dirname(packagePath), "types/index.d.ts");
  const program = ts.createProgram([declarationPath], { skipLibCheck: true });
  const checker = program.getTypeChecker();
  const source = program.getSourceFile(declarationPath)!;
  const exports = checker.getExportsOfModule(checker.getSymbolAtLocation(source)!);
  const values: string[] = [];
  const types: string[] = [];

  for (const entry of exports) {
    let symbol = entry;
    if (entry.flags & ts.SymbolFlags.Alias) {
      symbol = checker.getAliasedSymbol(entry);
    }

    const isTypeExport = entry.declarations?.some(declaration => {
      return ts.isExportSpecifier(declaration) &&
        (declaration.isTypeOnly || (declaration.parent.parent as ts.ExportDeclaration).isTypeOnly);
    });

    if (isTypeExport || !(symbol.flags & ts.SymbolFlags.Value)) {
      types.push(entry.name);
    } else {
      values.push(entry.name);
    }
  }

  values.sort();
  types.sort();
  writeSolidDeclarations(values, types);

  return [
    { from: "solid-js", imports: values },
    { from: "solid-js", imports: types, type: true }
  ];
}

function writeSolidDeclarations(values: string[], types: string[]): void {
  const declarations = [
    "// Generated by auto-imports.ts from the installed solid-js exports. Do not edit.",
    "export { };",
    "",
    "declare global {",
    ...values.map(name => `  const ${name}: typeof import("solid-js").${name};`),
    "}",
    "",
    "declare global {",
    "  // @ts-ignore Re-export generic types and the JSX namespace into the global scope.",
    "  export type {"
  ];

  let line = "    ";
  for (const name of types) {
    if (line.length + name.length + 2 > 120) {
      declarations.push(line.trimEnd());
      line = "    ";
    }

    line += `${name}, `;
  }

  declarations.push(line.trimEnd(), "  } from \"solid-js\";", "}", "");
  const content = declarations.join("\n");
  const file = new URL("./src/types/auto-imports.d.ts", import.meta.url);
  if (!existsSync(file) || readFileSync(file, "utf8") !== content) {
    writeFileSync(file, content);
  }
}
